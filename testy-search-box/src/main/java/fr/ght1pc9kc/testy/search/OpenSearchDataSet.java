package fr.ght1pc9kc.testy.search;

import java.util.List;

/**
 * Set of documents used to initialize an index with data.
 *
 * @param <T> Type of the elements to index as documents.
 */
@FunctionalInterface
public interface OpenSearchDataSet<T> {

    /**
     * Obtain the documents to index.
     *
     * @return Documents to index.
     */
    List<T> documents();

    /**
     * Name of the field holding the document {@code _id}. A field named {@code _id} is removed from the source,
     * as OpenSearch rejects metadata fields inside a document; any other field is kept.
     * Documents without this field get an id generated by OpenSearch.
     *
     * @return The identifier field name.
     */
    default String identifier() {
        return "_id";
    }
}
